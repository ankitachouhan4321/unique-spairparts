            const clearButton = document.getElementById("clearSearch");
            const resultText = document.getElementById("searchResultText");
            const noProducts = document.getElementById("noProductsFound");
            const products = document.querySelectorAll(".product-item");

            searchInput.addEventListener("input", function () {

                const searchValue = this.value.toLowerCase().trim();

                let visibleProducts = 0;

                products.forEach(function (product) {

                    const productName =
                        product.getAttribute("data-product-name").toLowerCase();

                    if (productName.includes(searchValue)) {

                        product.style.display = "";

                        visibleProducts++;

                    } else {

                        product.style.display = "none";

                    }

                });


                /* Show / hide clear button */
                if (searchValue !== "") {
                    clearButton.style.display = "block";
                } else {
                    clearButton.style.display = "none";
                }


                /* Result message */
                if (searchValue === "") {

                    resultText.textContent = "";

                } else if (visibleProducts > 0) {

                    resultText.textContent =
                        visibleProducts +
                        (visibleProducts === 1
                            ? " product found"
                            : " products found");

                } else {

                    resultText.textContent = "No products found";
                }


                /* No product message */
                if (visibleProducts === 0 && searchValue !== "") {

                    noProducts.style.display = "block";

                } else {

                    noProducts.style.display = "none";
                }

            });


            /* Clear search */
            clearButton.addEventListener("click", function () {

                searchInput.value = "";

                products.forEach(function (product) {
                    product.style.display = "";
                });

                clearButton.style.display = "none";
                resultText.textContent = "";
                noProducts.style.display = "none";

                searchInput.focus();

            });

        });
    </script>



